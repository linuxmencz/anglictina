// Dvě mezipaměti: kostra aplikace (s verzí; při nové verzi se stáhne znovu, je malá)
// a trvalé audio (nikdy se nemaže při aktivaci; doplňuje se po částech podle seznamu AUDIO).
const CACHE = 'anglictina-' + VERSION;
const AUDIO_CACHE = 'anglictina-audio';
const BATCH_SIZE = 4;       // kolik souborů se stahuje najednou
const SAVE_EVERY = 25;      // hashe se ukládají jednou za tolik dávek (soubor má ~160 KB)
const MIGRATE_CHUNK = 24;   // kolik záznamů se kopíruje najednou při migraci

const SCOPE = new URL('./', self.location).href;
const AUDIO_PREFIX = SCOPE + 'audio/';
const HASHES_KEY = SCOPE + '__audio-hashes.json'; // umělý záznam: cesta -> hash uloženého souboru
const WANTED = new Map(AUDIO); // cesta -> hash

// Cesta souboru vůči adrese aplikace (bez parametrů), např. 'audio/hello.mp3'.
function relPath(url) {
  const u = new URL(url, SCOPE);
  return u.href.slice(0, u.href.length - u.search.length - u.hash.length).slice(SCOPE.length);
}

function isAudioUrl(url) {
  return url.startsWith(AUDIO_PREFIX);
}

// crypto.subtle nemusí být dostupné; bez něj se soubory ukládají bez ověření (hash se nezapíše).
const canHash = typeof crypto !== 'undefined' && !!crypto.subtle;

// Prvních 8 hex znaků sha256 (stejně jako tools/build_sw.py); bez crypto.subtle vrací null.
async function sha8(buffer) {
  if (!canHash) return null;
  const digest = new Uint8Array(await crypto.subtle.digest('SHA-256', buffer));
  return Array.from(digest.slice(0, 4), (b) => b.toString(16).padStart(2, '0')).join('');
}

self.addEventListener('install', (event) => {
  // Jen kostra aplikace; audio se NESTAHUJE (řeší ho fillAudio na pokyn stránky).
  // cache: 'reload' obejde HTTP cache, aby se do verze neuložily zastaralé soubory.
  const requests = APP_FILES.map((f) => new Request(new URL(f, SCOPE).href, { cache: 'reload' }));
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(requests)).then(() => self.skipWaiting()));
});

// --- Migrace zvuku ze starých verzovaných mezipamětí ---
// Běží NA POZADÍ (activate jen převezme stránky), aby neblokovala fetch události; spouští ji
// i fillAudio. Selhání jednoho záznamu migraci nerozbije; stará mezipaměť se smaže až po čisté
// migraci. Dokud se nepřenese, handleAudio najde zvuk ve starých mezipamětích záložním hledáním.
let migration = null;

function ensureMigrated() {
  if (!migration) migration = migrateAndCleanup().finally(() => { migration = null; });
  return migration;
}

async function migrateAndCleanup() {
  try {
    const old = (await caches.keys()).filter((n) => n.startsWith('anglictina-') && n !== CACHE && n !== AUDIO_CACHE);
    if (!old.length) return;
    const target = await caches.open(AUDIO_CACHE);
    const have = new Set(await cachedAudioPaths());
    for (const name of old) {
      let clean = true;
      try {
        const source = await caches.open(name);
        const items = (await source.keys()).filter((r) => isAudioUrl(r.url)).map((r) => [r, relPath(r.url)]).filter(([, p]) => !have.has(p));
        for (let i = 0; i < items.length; i += MIGRATE_CHUNK) {
          await Promise.all(items.slice(i, i + MIGRATE_CHUNK).map(async ([request, path]) => {
            try {
              const response = await source.match(request);
              if (response) { await target.put(SCOPE + path, response); have.add(path); }
            } catch (e) { clean = false; }
          }));
        }
      } catch (e) { clean = false; }
      if (clean) { try { await caches.delete(name); } catch (e) { /* zkusí se příště */ } }
    }
  } catch (e) { /* migrace je jen optimalizace */ }
}

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
  ensureMigrated(); // bez čekání, viz výše
});

// --- Audio: hashe uložených souborů ---
// Hashe držíme v paměti (načtou se jednou) a na disk je zapisujeme zřídka, přes frontu zápisů.
let hashesPromise = null;
let persistQueue = Promise.resolve();

function getHashes() {
  if (!hashesPromise) {
    hashesPromise = (async () => {
      // Chyba čtení (I/O) projde ven a výsledek se nezapamatuje, aby se dobrý záznam nepřepsal prázdným.
      const cache = await caches.open(AUDIO_CACHE);
      const response = await cache.match(HASHES_KEY);
      if (!response) return {};
      try {
        const data = await response.json();
        return data && typeof data === 'object' && !Array.isArray(data) ? data : {};
      } catch (e) { return {}; } // nečitelný JSON = prázdný
    })();
    hashesPromise.catch(() => { hashesPromise = null; });
  }
  return hashesPromise;
}

function persistHashes() {
  const run = persistQueue.then(async () => {
    const hashes = await getHashes();
    const cache = await caches.open(AUDIO_CACHE);
    await cache.put(HASHES_KEY, new Response(JSON.stringify(hashes), { headers: { 'Content-Type': 'application/json' } }));
  });
  persistQueue = run.catch(() => {});
  return run;
}

async function cachedAudioPaths() {
  const cache = await caches.open(AUDIO_CACHE);
  return (await cache.keys()).filter((r) => isAudioUrl(r.url)).map((r) => relPath(r.url));
}

// Kolik souborů ze seznamu AUDIO je uloženo se shodným (ověřeným) hashem.
async function audioStatus() {
  const hashes = await getHashes();
  const present = new Set(await cachedAudioPaths());
  let cached = 0;
  for (const [path, hash] of AUDIO) if (present.has(path) && hashes[path] === hash) cached++;
  return { cached, total: AUDIO.length };
}

// --- Doplňování audia ---
let running = null;

// Volby pro stahování při doplňování: bez HTTP cache a (je-li k dispozici) s limitem 20 s.
function fetchOptions() {
  const options = { cache: 'no-cache' };
  if (typeof AbortSignal !== 'undefined' && typeof AbortSignal.timeout === 'function') options.signal = AbortSignal.timeout(20000);
  return options;
}

function fillAudio(onProgress) {
  if (!running) running = doFill(onProgress).finally(() => { running = null; });
  return running;
}

async function doFill(onProgress) {
  await ensureMigrated();
  const cache = await caches.open(AUDIO_CACHE);
  const hashes = await getHashes();
  const present = new Set(await cachedAudioPaths());

  // Soubory, které už v seznamu nejsou, smažeme.
  for (const path of [...present]) {
    if (!WANTED.has(path)) { await cache.delete(SCOPE + path); present.delete(path); }
  }
  for (const path of Object.keys(hashes)) if (!WANTED.has(path)) delete hashes[path];

  // Záznam bez uloženého hashe (z migrace nebo ztraceného souboru s hashi) nevěříme naslepo:
  // spočítáme hash jeho těla a přijmeme ho, jen když sedí s AUDIO; jinak se stáhne znovu.
  const unverified = [...present].filter((p) => hashes[p] === undefined);
  let verified = 0;
  let savedAt = 0;
  for (let i = 0; i < unverified.length; i += 16) {
    await Promise.all(unverified.slice(i, i + 16).map(async (path) => {
      try {
        const response = await cache.match(SCOPE + path);
        if (response && (await sha8(await response.arrayBuffer())) === WANTED.get(path)) { hashes[path] = WANTED.get(path); verified++; }
      } catch (e) { /* zůstane neověřený a stáhne se znovu */ }
    }));
    if (verified - savedAt >= 500) { savedAt = verified; await persistHashes().catch(() => {}); } // přežije ukončení workeru
  }

  const todo = AUDIO.filter(([path, hash]) => !present.has(path) || hashes[path] !== hash);
  let cached = AUDIO.length - todo.length;
  const report = () => { if (onProgress) onProgress({ cached, total: AUDIO.length }); };
  if (unverified.length) { await persistHashes().catch(() => {}); report(); }

  try {
    for (let i = 0, batches = 0; i < todo.length; i += BATCH_SIZE, batches++) {
      const results = await Promise.all(todo.slice(i, i + BATCH_SIZE).map(async ([path, hash]) => {
        let response;
        try {
          response = await fetch(path, fetchOptions()); // bez HTTP cache, ať nedostaneme starou verzi
        } catch (e) {
          // Vypršený limit = jen přeskočený soubor, ne důvod k zastavení (to je pro „jsme offline“).
          return { failed: true, network: !(e && e.name === 'TimeoutError') };
        }
        try {
          if (!response.ok || response.status !== 200) return { failed: true };
          const buffer = await response.arrayBuffer();
          const actual = await sha8(buffer);
          if (canHash && actual !== hash) return { failed: true }; // zastaralá/poškozená data neukládáme
          await cache.put(SCOPE + path, new Response(buffer, { headers: { 'Content-Type': response.headers.get('Content-Type') || 'audio/mpeg' } }));
          return canHash ? { path, hash } : { path, unverified: true };
        } catch (e) {
          return { failed: true };
        }
      }));
      for (const r of results) if (!r.failed && !r.unverified) { hashes[r.path] = r.hash; cached++; }
      if ((batches + 1) % SAVE_EVERY === 0) await persistHashes().catch(() => {});
      report();
      // Když selhal každý požadavek v dávce kvůli síti, jsme offline: tiše skončíme.
      if (results.every((r) => r.network)) break;
    }
  } finally {
    await persistHashes().catch(() => {});
  }
  report();
}

function broadcast(message) {
  return self.clients.matchAll({ type: 'window' }).then((all) => all.forEach((c) => c.postMessage(message)));
}

self.addEventListener('message', (event) => {
  const type = event.data && event.data.type;
  if (type === 'fill-audio') {
    const progress = ({ cached, total }) => { broadcast({ type: 'audio-progress', cached, total }); };
    event.waitUntil(fillAudio(progress).catch(() => {}));
  } else if (type === 'audio-status') {
    event.waitUntil(audioStatus().then(({ cached, total }) => {
      if (event.source) event.source.postMessage({ type: 'audio-progress', cached, total });
    }));
  }
});

// Safari žádá o zvuk po částech (hlavička Range); z mezipaměti proto musíme umět vrátit část souboru.
async function rangeResponse(request, response) {
  const buffer = await response.arrayBuffer();
  const match = /bytes=(\d*)-(\d*)/.exec(request.headers.get('range'));
  const size = buffer.byteLength;
  let start = match && match[1] !== '' ? Number(match[1]) : 0;
  let end = match && match[2] !== '' ? Number(match[2]) : size - 1;
  if (match && match[1] === '' && match[2] !== '') { // „posledních N bajtů“
    start = Math.max(0, size - Number(match[2]));
    end = size - 1;
  }
  end = Math.min(end, size - 1);
  if (!match || start > end || start >= size) {
    return new Response(null, { status: 416, headers: { 'Content-Range': `bytes */${size}` } });
  }
  const part = buffer.slice(start, end + 1);
  return new Response(part, {
    status: 206,
    headers: {
      'Content-Type': response.headers.get('Content-Type') || 'audio/mpeg',
      'Content-Range': `bytes ${start}-${end}/${size}`,
      'Content-Length': String(part.byteLength),
    },
  });
}

// Uloží stažený zvuk a zapíše hash, jen když tělo sedí s AUDIO (jinak ho ověří až fillAudio).
async function storeFetched(path, response) {
  const buffer = await response.arrayBuffer();
  const cache = await caches.open(AUDIO_CACHE);
  await cache.put(SCOPE + path, new Response(buffer, { headers: { 'Content-Type': response.headers.get('Content-Type') || 'audio/mpeg' } }));
  if (WANTED.has(path) && canHash && (await sha8(buffer)) === WANTED.get(path)) {
    const hashes = await getHashes();
    hashes[path] = WANTED.get(path);
    await persistHashes();
  }
}

// event.waitUntil může vyhodit (např. po dokončení události); odpověď uživateli tím nesmí utrpět.
function keepAlive(event, promise) {
  try { event.waitUntil(promise); } catch (e) { /* best effort */ }
}

// Jedno stahování na cestu: víc požadavků (např. Range) na týž nenačtený soubor sdílí jeden přenos.
const downloads = new Map();

async function downloadAudio(url, event) {
  const path = relPath(url);
  let response = downloads.get(path);
  if (!response) {
    response = fetch(url, { cache: 'no-cache' }); // celý soubor, bez Range
    downloads.set(path, response);
    // Ukládání je „best effort“: jeho selhání nesmí změnit odpověď uživateli.
    const stored = response
      .then((r) => (r.ok && r.status === 200 ? storeFetched(path, r.clone()) : undefined))
      .catch(() => {})
      .finally(() => downloads.delete(path));
    keepAlive(event, stored);
  }
  return (await response).clone();
}

// Hledání zvuku: nejdřív trvalá mezipaměť, potom (než doběhne migrace) všechny ostatní.
async function lookupAudio(url, event) {
  try {
    const audio = await caches.open(AUDIO_CACHE);
    const hit = await audio.match(url, { ignoreSearch: true });
    if (hit) return hit;
    const other = await caches.match(url, { ignoreSearch: true });
    if (other) {
      const copy = other.clone();
      keepAlive(event, audio.put(SCOPE + relPath(url), copy).catch(() => {}));
      return other;
    }
    // Migrace mohla záznam mezitím přesunout a smazat starý: ještě jednou trvalá mezipaměť.
    return await audio.match(url, { ignoreSearch: true });
  } catch (e) { /* mezipaměť nejde číst: zkusíme síť */ }
  return undefined;
}

async function handleAudio(request, event) {
  let response = await lookupAudio(request.url, event);
  if (!response) {
    try {
      response = await downloadAudio(request.url, event);
    } catch (e) {
      return Response.error();
    }
    if (!response.ok || response.status !== 200) return response;
  }
  return request.headers.get('range') ? rangeResponse(request, response) : response;
}

async function handle(request, event) {
  if (isAudioUrl(request.url)) return handleAudio(request, event);
  const cache = await caches.open(CACHE);
  let response = await cache.match(request, { ignoreSearch: true });
  if (!response && request.mode === 'navigate') response = await cache.match('index.html');
  if (!response) {
    try {
      return await fetch(request);
    } catch (e) {
      return Response.error();
    }
  }
  return request.headers.get('range') ? rangeResponse(request, response) : response;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(handle(request, event));
});
